/**
 * Demo catalog of Bakht Stroy Company (Dushanbe): 5 directions × 3 subcategories × 10 products = 150,
 * prices in somoni (stored in dirams), generated pictures. Not created in production.
 * Safe to run again: categories and products are matched by name.
 */
class CatalogSeeder extends Seeder
{
    public function run(): void
    {
        if (app()->isProduction()) {
            $this->command?->warn('CatalogSeeder: demo catalog is skipped in production.');

            return;
        }

        $rootSort = 0;

        foreach ($this->catalog() as $rootName => $root) {
            $rootCategory = $this->category($rootName, null, $rootSort++, $root['description'], $root['icon'], $root['palette']);

            $childSort = 0;
            foreach ($root['children'] as $childName => $child) {
                $category = $this->category($childName, $rootCategory->id, $childSort++, null, $child['icon'], $root['palette']);

                foreach ($child['products'] as $row) {
                    $this->product($category, $child['icon'], $root['palette'], ...$row);
                }
            }

            $this->command?->info("CatalogSeeder: {$rootName} ✓");
        }

        $this->command?->info('CatalogSeeder: '.Category::query()->count().' categories, '.Product::query()->count().' products.');
    }

    /**
     * @param  array{0: string, 1: string}  $palette
     */
    private function category(string $name, ?int $parentId, int $sort, ?string $description, string $icon, array $palette): Category
    {
        $category = Category::query()->firstOrCreate(
            ['name' => $name, 'parent_id' => $parentId],
            ['slug' => UniqueSlug::for(Category::class, $name), 'sort_order' => $sort, 'is_active' => true, 'description' => $description],
        );

        if (! $category->hasMedia(Category::IMAGE_COLLECTION)) {
            $category->addMedia(DemoImage::category($name, $icon, $palette))
                ->usingName($name)
                ->usingFileName($category->slug.'.png')
                ->toMediaCollection(Category::IMAGE_COLLECTION);
        }

        return $category;
    }

    /**
     * @param  array{0: string, 1: string}  $palette
     * @param  array<string, string>  $specs
     * @param  float  $price  in somoni (stored in dirams)
     */
    private function product(
        Category $category,
        string $icon,
        array $palette,
        string $name,
        float $price,
        U $unit,
        int $stock,
        array $specs,
        int $minOrder = 1,
        bool $featured = false,
        ?float $oldPrice = null,
    ): void {
        $product = Product::query()->firstOrNew(['name' => $name]);

        $product->fill([
            'category_id' => $category->id,
            'slug' => $product->exists ? $product->slug : UniqueSlug::for(Product::class, $name),
            'description' => $this->description($name, $category->name, $specs),
            'price' => (int) round($price * 100),
            'old_price' => $oldPrice !== null ? (int) round($oldPrice * 100) : null,
            'unit' => $unit,
            'stock' => $stock,
            'min_order_qty' => $minOrder,
            'specs' => collect($specs)->map(fn (string $value, string $key) => ['name' => $key, 'value' => $value])->values()->all(),
            'is_active' => true,
            'is_featured' => $featured,
        ])->save();

        if ($product->sku === null) {
            $product->forceFill(['sku' => sprintf('BS-%06d', $product->id)])->save();
        }

        if (! $product->hasMedia(Product::IMAGES_COLLECTION)) {
            $subtitle = implode(' · ', array_slice(array_values($specs), 0, 3));

            $product->addMedia(DemoImage::product($name, $subtitle, $icon, $palette))
                ->usingName($name)
                ->usingFileName($product->slug.'.png')
                ->toMediaCollection(Product::IMAGES_COLLECTION);
        }
    }

    /**
     * @param  array<string, string>  $specs
     */
    private function description(string $name, string $category, array $specs): string
    {
        $details = collect($specs)->map(fn (string $value, string $key) => mb_strtolower($key).' — '.$value)->implode('; ');

