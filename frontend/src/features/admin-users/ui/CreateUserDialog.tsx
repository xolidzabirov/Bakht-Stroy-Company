"use client";

import { useRouter } from "next/navigation";
import { useMemo, useState } from "react";
import { Controller, useForm, useWatch } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import { z } from "zod";
import { LoaderCircle, UserPlus } from "lucide-react";
import { applyApiErrors, bff } from "@/shared/api/client";
import type { AdminUser } from "@/shared/api/types";
import { useI18n } from "@/shared/i18n/client";
import type { Dictionary } from "@/shared/i18n/dictionaries";
import { cn } from "@/shared/lib/cn";
import { Button, Field, FormAlert, PasswordInput, TextInput } from "@/shared/ui";
import { Dialog, DialogContent, DialogDescription, DialogTitle } from "@/shared/ui/kit/dialog";
import { PhoneInput } from "@/shared/ui/PhoneInput";
import { type Credentials, CredentialsCard } from "./CredentialsCard";

function createSchema(t: Dictionary) {
  const v = t.admin.users.validation;

  return z
    .object({
      name: z.string().trim().min(2, v.name).max(100),
      email: z.string().trim().email(v.email).max(255),
      phone: z.string().regex(/^(\d{9})?$/, v.phone),
      role: z.enum(["manager", "client"]),
      passwordMode: z.enum(["auto", "own"]),
      password: z.string(),
    })
    .superRefine((data, ctx) => {
      if (data.passwordMode === "own" && !/^(?=.*\p{L})(?=.*\d).{8,100}$/u.test(data.password)) {
        ctx.addIssue({ code: "custom", path: ["password"], message: v.password });
      }
    });
}

type Values = z.infer<ReturnType<typeof createSchema>>;

const defaults: Values = { name: "", email: "", phone: "", role: "manager", passwordMode: "auto", password: "" };

/** Two or more choices as pill buttons (a radio group under the hood). */
function Choice<T extends string>({ name, value, options, onChange }: { name: string; value: T; options: { value: T; label: string }[]; onChange: (value: T) => void }) {
  return (
    <div role="radiogroup" className="flex flex-wrap gap-2">
      {options.map((option) => (
        <label
          key={option.value}
          className={cn(
            "inline-flex h-10 cursor-pointer items-center rounded-xl border px-4 text-sm font-semibold transition has-[:focus-visible]:ring-[3px] has-[:focus-visible]:ring-ring/50",
            value === option.value ? "border-ink bg-ink text-white dark:border-white dark:bg-white dark:text-ink" : "border-border hover:border-foreground/40",
          )}
        >
          <input type="radio" name={name} value={option.value} checked={value === option.value} onChange={() => onChange(option.value)} className="sr-only" />
          {option.label}
        </label>
      ))}
    </div>
  );
}

/**
 * "Добавить пользователя" (administrator): a ready account — e.g. a new manager — and its sign-in details
 * to hand over. The password is generated by the server unless the admin types one.
 */
export function CreateUserDialog() {
  const { t } = useI18n();
  const u = t.admin.users;
  const router = useRouter();
  const [open, setOpen] = useState(false);
  const [result, setResult] = useState<{ credentials: Credentials; phone: string | null } | null>(null);
  const [formError, setFormError] = useState<string | null>(null);
  const schema = useMemo(() => createSchema(t), [t]);

  const {
    register,
    handleSubmit,
    control,
    reset,
    setError,
    formState: { errors, isSubmitting },
  } = useForm<Values>({ resolver: zodResolver(schema), defaultValues: defaults });
  const passwordMode = useWatch({ control, name: "passwordMode" });

  const close = (next: boolean) => {
    setOpen(next);
    if (!next) {
      setResult(null);
      setFormError(null);
      reset(defaults);
    }
  };

  const onSubmit = handleSubmit(async (values) => {
    setFormError(null);
    const phone = values.phone ? `+992${values.phone}` : null;
    try {
      const response = await bff<{ data: { user: AdminUser; credentials: Credentials } }>("/api/proxy/admin/users", {
        body: { name: values.name, email: values.email, phone, role: values.role, password: values.passwordMode === "own" ? values.password : null },
      });
      setResult({ credentials: response.data.credentials, phone });
      router.refresh();
    } catch (error) {
      setFormError(applyApiErrors(error, setError, ["name", "email", "phone", "role", "password"], t.errors));
    }
  });

  return (
    <>
      <Button onClick={() => setOpen(true)}>
        <UserPlus className="size-4" />
        {u.add}
      </Button>

      <Dialog open={open} onOpenChange={close}>
        <DialogContent className="max-h-[92dvh] overflow-y-auto rounded-2xl sm:max-w-lg">
          {result ? (
            <>
              <DialogTitle className="text-xl font-extrabold">{u.created}</DialogTitle>
              <DialogDescription>{t.admin.credentials.title}</DialogDescription>
              <CredentialsCard credentials={result.credentials} phone={result.phone} />
              <Button variant="outline" onClick={() => close(false)}>
                {t.admin.credentials.done}
              </Button>
            </>
          ) : (
            <form onSubmit={onSubmit} noValidate className="space-y-4">
              <div>
                <DialogTitle className="text-xl font-extrabold">{u.createTitle}</DialogTitle>
                <DialogDescription className="mt-1">{u.createText}</DialogDescription>
              </div>
              {formError && <FormAlert>{formError}</FormAlert>}

              <Field label={u.name} error={errors.name?.message}>
                {(id, describedBy) => <TextInput id={id} autoComplete="off" aria-invalid={Boolean(errors.name)} aria-describedby={describedBy} {...register("name")} />}
              </Field>
              <Field label={u.email} error={errors.email?.message}>
                {(id, describedBy) => <TextInput id={id} type="email" autoComplete="off" aria-invalid={Boolean(errors.email)} aria-describedby={describedBy} {...register("email")} />}
              </Field>
              <Field label={u.phone} error={errors.phone?.message}>
                {(id, describedBy) => (
                  <Controller
                    control={control}
                    name="phone"
                    render={({ field }) => (
                      <PhoneInput id={id} value={field.value} onChange={field.onChange} onBlur={field.onBlur} placeholder="93 123 45 67" aria-invalid={Boolean(errors.phone)} aria-describedby={describedBy} />
                    )}
                  />
                )}
              </Field>

              <fieldset>
                <legend className="mb-1.5 text-sm font-semibold">{u.roleLabel}</legend>
                <Controller
                  control={control}
                  name="role"
                  render={({ field }) => (
                    <Choice name="role" value={field.value} onChange={field.onChange} options={[{ value: "manager", label: u.roles.manager }, { value: "client", label: u.roles.client }]} />
                  )}
                />
              </fieldset>

              <fieldset className="space-y-3">
                <legend className="mb-1.5 text-sm font-semibold">{u.password}</legend>
                <Controller
                  control={control}
                  name="passwordMode"
                  render={({ field }) => (
                    <Choice name="passwordMode" value={field.value} onChange={field.onChange} options={[{ value: "auto", label: u.passwordAuto }, { value: "own", label: u.passwordOwn }]} />
                  )}
                />
                {passwordMode === "own" && (
                  <Field label={u.password} error={errors.password?.message} hint={u.passwordHint}>
                    {(id, describedBy) => <PasswordInput id={id} autoComplete="new-password" aria-invalid={Boolean(errors.password)} aria-describedby={describedBy} {...register("password")} />}
                  </Field>
                )}
              </fieldset>

              <div className="flex flex-wrap justify-end gap-2 pt-1">
                <Button type="button" variant="outline" onClick={() => close(false)}>
                  {t.admin.common.cancel}
                </Button>
                <Button type="submit" disabled={isSubmitting}>
                  {isSubmitting ? <LoaderCircle className="size-4 animate-spin" /> : <UserPlus className="size-4" />}
                  {u.create}
                </Button>
              </div>
            </form>
          )}
        </DialogContent>
      </Dialog>
    </>
  );
}
